package dev.cobolonjava.runtime.config;

/**
 * 参照実装の仕様書自身が「結果は保証されない」と明言している領域の扱い (要件 FR-205)。
 *
 * <p>既定は {@link #SAFE}。データが宣言どおりに収まっている限り両モードの結果は一致するため、
 * 既定を安全側に置くことによる実害は、元々未定義であったケースに限定される。
 */
public enum UndefinedBehavior {

    /** 定義された挙動を返す。診断が必要な場合は警告を出す。 */
    SAFE,

    /**
     * ホストの実装上の挙動を模倣する。
     *
     * <p>このモードで模倣する挙動には V2 の裏付けがない (要件 FR-206、リスク R-9)。
     * 有効にした実行では、その旨を実行時ログへ記録しなければならない。
     */
    MIMIC
}
